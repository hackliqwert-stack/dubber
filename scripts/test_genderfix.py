import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "server"))
from app import genderfix  # noqa: E402

CASES = [
    # (text, speaker gender, expected)
    ("Я уверена, что ничего из этого не случилось бы, если бы меня не уволили из Apple.", "m",
     "Я уверен, что ничего из этого не случилось бы, если бы меня не уволили из Apple."),
    ("Я убеждена, что единственное, что держало меня в живых - это то, что я любила свою работу.", "m",
     "Я убеждён, что единственное, что держало меня в живых - это то, что я любил свою работу."),
    ("И с тех пор я смотрела в зеркало каждое утро и спрашивала себя.", "m",
     "И с тех пор я смотрел в зеркало каждое утро и спрашивал себя."),
    # traps: must stay unchanged
    ("Я думаю, это была ошибка.", "m", "Я думаю, это была ошибка."),
    ("Меня удивила эта история.", "m", "Меня удивила эта история."),
    ("Я видел, как она пришла и она сказала правду.", "m", "Я видел, как она пришла и она сказала правду."),
    ("Моя работа была сложной.", "m", "Моя работа была сложной."),
    ("Мы пошли домой, и я устала.", "m", "Мы пошли домой, и я устал."),
    # female speaker
    ("Я был уверен, что я знал это.", "f", "Я была уверена, что я знала это."),
    ("Он сказал, что я пришёл.", "f", "Он сказал, что я пришла."),
    ("Он сказал, что я пришёл, и он был рад.", "f", "Он сказал, что я пришла, и он был рад."),
    # no gender -> untouched
    ("Я уверена.", None, "Я уверена."),
]

bad = 0
for text, g, want in CASES:
    got = genderfix.fix(text, g)
    ok = got == want
    bad += not ok
    print(("OK  " if ok else "FAIL"), g, "|", got if ok else f"{got}   (expected: {want})")
sys.exit(1 if bad else 0)
